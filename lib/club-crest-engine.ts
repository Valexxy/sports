/**
 * Returns a high-definition official logo URL for any world club, with fuzzy name matching.
 */
export function getClubCrest(teamName: string, fallbackUrl?: string): string {
  if (!teamName) return fallbackUrl || 'https://crests.football-data.org/PL.png';
  const norm = teamName.toLowerCase().trim();

  // Exact match
  if (OFFICIAL_CLUB_CRESTS[norm]) return OFFICIAL_CLUB_CRESTS[norm];

  // Substring match
  for (const [name, crest] of Object.entries(OFFICIAL_CLUB_CRESTS)) {
    if (norm.includes(name) || name.includes(norm)) {
      return crest;
    }
  }

  return fallbackUrl || 'https://crests.football-data.org/PL.png';
}
